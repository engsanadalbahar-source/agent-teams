"""
Token counter module using tiktoken (cl100k_base / o200k_base).
Provides exact token counting for prompts, tool calls, and conversation histories.
"""

import sys
try:
    import tiktoken
    _ENCODER = tiktoken.get_encoding("cl100k_base")
except ImportError:
    _ENCODER = None


def count_tokens(text: str) -> int:
    """Return the exact token count for a text string."""
    if not text:
        return 0
    if _ENCODER is not None:
        return len(_ENCODER.encode(text))
    # Fallback approximation if tiktoken is not available
    # ~4 characters per token for English text/code
    return max(1, len(text) // 4)


def count_message(role: str, content: str) -> int:
    """Return token count for a single chat message including role framing."""
    # LLM formatting overhead: ~3 tokens per message for role, start/end tokens
    return 3 + count_tokens(role) + count_tokens(content)


class ConversationTracker:
    """Tracks token consumption across a multi-turn conversation or agent session."""
    def __init__(self, name: str, system_prompt: str = ""):
        self.name = name
        self.system_prompt = system_prompt
        self.messages: list[dict[str, str]] = []
        if system_prompt:
            self.messages.append({"role": "system", "content": system_prompt})
        
        self.turns_history: list[dict] = []
        self.cumulative_input_tokens = 0
        self.cumulative_output_tokens = 0
        self.peak_context_tokens = 0

    def get_current_context_size(self) -> int:
        """Calculate the total tokens currently in the conversation history."""
        total = 0
        for msg in self.messages:
            total += count_message(msg["role"], msg["content"])
        return total

    def add_turn(self, user_or_tool_input: str, assistant_output: str, input_role: str = "user") -> dict:
        """
        Simulate an LLM turn:
        1. Context sent to model = all existing messages + new input.
        2. Model generates assistant_output.
        3. Both are appended to history.
        """
        # Tokens sent to model as prompt
        input_msg_tokens = count_message(input_role, user_or_tool_input)
        prompt_tokens = self.get_current_context_size() + input_msg_tokens
        
        # Tokens generated by model
        output_tokens = count_tokens(assistant_output)
        
        # Update conversation history
        self.messages.append({"role": input_role, "content": user_or_tool_input})
        self.messages.append({"role": "assistant", "content": assistant_output})
        
        # Record stats
        self.cumulative_input_tokens += prompt_tokens
        self.cumulative_output_tokens += output_tokens
        new_context_size = prompt_tokens + output_tokens
        if new_context_size > self.peak_context_tokens:
            self.peak_context_tokens = new_context_size

        turn_stat = {
            "turn_index": len(self.turns_history) + 1,
            "prompt_tokens": prompt_tokens,
            "output_tokens": output_tokens,
            "context_size_after": new_context_size,
        }
        self.turns_history.append(turn_stat)
        return turn_stat

    def get_summary(self) -> dict:
        return {
            "name": self.name,
            "turns_count": len(self.turns_history),
            "cumulative_input_tokens": self.cumulative_input_tokens,
            "cumulative_output_tokens": self.cumulative_output_tokens,
            "total_billed_tokens": self.cumulative_input_tokens + self.cumulative_output_tokens,
            "peak_context_tokens": self.peak_context_tokens,
        }
